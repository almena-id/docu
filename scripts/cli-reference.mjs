// The CLI reference (`task refs`): every `almena` command, read from the
// binary's own help (clap), one page per command group under
// src/content/docs/reference/cli/, plus its index. Never edit those pages:
// regenerate them. ALMENA_BIN names the binary (default: a ../almena debug
// build, `cargo build` there first).
import { spawnSync } from "node:child_process";
import { mkdir, rm, writeFile } from "node:fs/promises";

const BIN = process.env.ALMENA_BIN ?? "../almena/target/debug/almena";
const OUT = "src/content/docs/reference/cli";
const NOTICE = "{/* Generated by scripts/cli-reference.mjs from `almena --help`: do not edit, run `task refs`. */}";

function help(path) {
  const run = spawnSync(BIN, [...path, "--help"], {
    encoding: "utf8",
    // A fixed width, so the text wraps the same on every machine.
    env: { ...process.env, COLUMNS: "100", NO_COLOR: "1" },
  });
  if (run.status !== 0) throw new Error(`almena ${path.join(" ")} --help: ${run.stderr}`);
  return run.stdout.replace(/\s+$/, "");
}

/** About, usage, subcommands and the rest (arguments, options) of one help. */
function parse(text) {
  const [about = "", ...rest] = text.split(/\n\n(?=Usage:)/);
  const body = rest.join("\n\n");
  const usage = (body.match(/^Usage: (.*)$/m) ?? [])[1] ?? "";
  const commands = [];
  const block = body.match(/\nCommands:\n([\s\S]*?)(?:\n\n(?=\S)|$)/);
  if (block)
    for (const line of block[1].split("\n")) {
      const named = line.match(/^ {2}(\S+)\s{2,}(.*)$/);
      if (named) commands.push({ name: named[1], about: named[2].trim() });
      else if (commands.length && line.trim()) commands.at(-1).about += ` ${line.trim()}`;
    }
  const details = body
    .replace(/^Usage: .*$/m, "")
    .replace(/\nCommands:\n[\s\S]*?(?:\n\n(?=\S)|$)/, "\n")
    .trim();
  return { about: about.trim(), usage, commands: commands.filter((c) => c.name !== "help"), details };
}

function walk(path = []) {
  const node = { path, ...parse(help(path)) };
  node.children = node.commands.map((command) => walk([...path, command.name]));
  return node;
}

const code = (text) => `\`\`\`text\n${text}\n\`\`\``;
const anchor = (path) => path.join("-");
const firstLine = (text) => text.split("\n")[0];
const yaml = (text) => JSON.stringify(text);

function section(node, depth) {
  const heading = `${"#".repeat(depth)} \`almena ${node.path.join(" ")}\``;
  const parts = [heading, node.about, code(`Usage: ${node.usage}`)];
  if (node.details) parts.push(code(node.details));
  for (const child of node.children) parts.push(section(child, Math.min(depth + 1, 4)));
  return parts.filter(Boolean).join("\n\n");
}

/** An Options/Arguments text as its entries: each starts at column 2 or 6. */
function entries(details) {
  const out = [];
  for (const line of details.split("\n")) {
    if (/^(\S| {2}\S| {6}-)/.test(line)) out.push([line]);
    else if (out.length) out.at(-1).push(line);
  }
  return out;
}

/** A command's own arguments and options: without those every command takes
 * (listed once, on the index) and without --help. */
function own(details, global) {
  const kept = entries(details).filter(([head]) => {
    const name = head.trim().split(/\s{2,}/)[0];
    return !global.has(name) && !/^-h, --help/.test(head.trim());
  });
  // Drop a section heading left with nothing under it.
  const lines = kept.map((entry) => entry.join("\n").replace(/\s+$/, ""));
  const heading = (block) => /^\S.*:$/.test(block);
  return lines
    .filter((block, i) => !(heading(block) && (i === lines.length - 1 || heading(lines[i + 1]))))
    .map((block, i, all) => (heading(block) || i === all.length - 1 ? block : `${block}\n`))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const root = walk();
const global = new Set(
  entries(root.details)
    .map(([head]) => head.trim().split(/\s{2,}/)[0])
    .filter((name) => name.startsWith("-")),
);
const prune = (node) => {
  node.details = own(node.details, global);
  node.children.forEach(prune);
};
root.children.forEach(prune);
const version = spawnSync(BIN, ["--version"], { encoding: "utf8" }).stdout.trim();
await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const groups = root.children.filter((node) => node.path[0] !== "completions");
for (const [index, group] of groups.entries()) {
  const page = [
    "---",
    `title: almena ${group.path[0]}`,
    `description: ${yaml(firstLine(group.about))}`,
    `sidebar: { order: ${index + 1} }`,
    "---",
    "",
    NOTICE,
    "",
    group.about,
    "",
    group.children.length
      ? group.children
          .map((child) => `- [\`${child.path.join(" ")}\`](#almena-${anchor(child.path)}) — ${child.about}`)
          .join("\n")
      : "",
    "",
    group.children.map((child) => section(child, 2)).join("\n\n"),
    group.children.length ? "" : code(`Usage: ${group.usage}\n\n${group.details}`),
    "",
  ];
  await writeFile(`${OUT}/${group.path[0]}.mdx`, page.join("\n").replace(/\n{3,}/g, "\n\n"));
}

const index = [
  "---",
  "title: almena CLI",
  "description: Every command of the almena command-line client, from its own help.",
  "sidebar: { order: 0, label: Overview }",
  "---",
  "",
  NOTICE,
  "",
  `${root.about}. This reference is read from the binary itself (\`${version}\`): what each command says when asked for \`--help\`.`,
  "",
  "Install it and make your first call with the [quick start](/integrate/quick-start/).",
  "",
  "## Commands",
  "",
  "| Command | What it does |",
  "| --- | --- |",
  ...groups.map((group) => `| [\`almena ${group.path[0]}\`](/reference/cli/${group.path[0]}/) | ${group.about.replace(/\|/g, "\\|")} |`),
  "| `almena completions <shell>` | Print the shell completion script (bash, zsh, fish, PowerShell) |",
  "",
  "## Options for every command",
  "",
  code(root.details),
  "",
];
await writeFile(`${OUT}/index.mdx`, index.join("\n"));
console.log(`${OUT}: ${groups.length} groups, ${version}`);
