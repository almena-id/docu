// The API reference (`task refs`): every operation of src/data/openapi.json,
// one page per tag under src/content/docs/reference/api/, the schemas they
// use on a page of their own, and the index. Never edit those pages:
// regenerate them (`task refs` reads the OpenAPI document from ../api first).
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";

const OUT = "src/content/docs/reference/api";
const NOTICE = "<!-- Generated by scripts/api-reference.mjs from src/data/openapi.json: do not edit, run `task refs`. -->";
const spec = JSON.parse(await readFile("src/data/openapi.json", "utf8"));
const schemas = spec.components?.schemas ?? {};

const NAMES = { did: "DIDs", mcp: "MCP", "status lists": "Status lists" };
const title = (tag) => NAMES[tag] ?? tag.charAt(0).toUpperCase() + tag.slice(1);
const slug = (tag) => tag.toLowerCase().replace(/[^a-z0-9]+/g, "-");
const CODE = /`([a-z][a-z0-9]*(?:_[a-z0-9]+)+)`/g;
// The codes the errors page has an anchor for (ErrorCodes.astro).
const refusals = spec["x-refusals"] ?? {};

/** Markdown text, safe: what is outside code spans cannot open HTML. */
function text(value = "") {
  return value
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, "&lt;").replace(/>/g, "&gt;")))
    .join("");
}
const cell = (value) => text(value).replace(/\|/g, "\\|").replace(/\n+/g, " ");
const refName = (ref) => ref.split("/").at(-1);
const schemaLink = (name) => `[${name}](/reference/api/schemas/#${name.toLowerCase()})`;

/** A schema as a short type: `string (uuid)`, `array of X`, `X or null`. */
function type(schema = {}) {
  if (schema.$ref) return schemaLink(refName(schema.$ref));
  if (schema.anyOf || schema.oneOf) {
    const kinds = (schema.anyOf ?? schema.oneOf).map(type);
    return [...new Set(kinds)].join(" or ");
  }
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(", ");
  if (schema.type === "array") return `array of ${type(schema.items)}`;
  if (schema.type === "object" && schema.additionalProperties && typeof schema.additionalProperties === "object")
    return `map of ${type(schema.additionalProperties)}`;
  const kind = schema.type ?? "any";
  return schema.format ? `${kind} (${schema.format})` : kind;
}

/** What limits a value: lengths, ranges, a pattern, a default. */
function limits(schema = {}) {
  const found = [];
  const of = schema.anyOf?.find((option) => option.type !== "null") ?? schema;
  if (of.minLength !== undefined) found.push(`min length ${of.minLength}`);
  if (of.maxLength !== undefined) found.push(`max length ${of.maxLength}`);
  if (of.minimum !== undefined) found.push(`≥ ${of.minimum}`);
  if (of.maximum !== undefined) found.push(`≤ ${of.maximum}`);
  if (of.minItems !== undefined) found.push(`at least ${of.minItems}`);
  if (of.maxItems !== undefined) found.push(`at most ${of.maxItems}`);
  if (of.pattern) found.push(`pattern \`${of.pattern}\``);
  if (schema.default !== undefined && schema.default !== null) found.push(`default \`${JSON.stringify(schema.default)}\``);
  return found.join(", ");
}

function fields(schema) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  if (!Object.keys(properties).length) return "";
  const rows = Object.entries(properties).map(
    ([name, field]) =>
      `| \`${name}\`${required.has(name) ? "" : " *(optional)*"} | ${type(field)} | ${cell([field.description, limits(field)].filter(Boolean).join(" — "))} |`,
  );
  return ["| Field | Type | Notes |", "| --- | --- | --- |", ...rows].join("\n");
}

function body(operation) {
  const content = operation.requestBody?.content ?? {};
  const [media, { schema } = {}] = Object.entries(content)[0] ?? [];
  if (!media) return "";
  const shown = schema?.$ref ? schemas[refName(schema.$ref)] : schema;
  return [
    `**Body** (\`${media}\`): ${type(schema)}`,
    shown ? fields(shown) : "",
  ]
    .filter(Boolean)
    .join("\n\n");
}

function parameters(operation) {
  const list = operation.parameters ?? [];
  if (!list.length) return "";
  return [
    "| Parameter | In | Type | Notes |",
    "| --- | --- | --- | --- |",
    ...list.map(
      (p) =>
        `| \`${p.name}\`${p.required ? "" : " *(optional)*"} | ${p.in} | ${type(p.schema)} | ${cell([p.description, limits(p.schema ?? {})].filter(Boolean).join(" — "))} |`,
    ),
  ].join("\n");
}

function responses(operation) {
  const rows = Object.entries(operation.responses ?? {}).map(([status, response]) => {
    const schema = Object.values(response.content ?? {})[0]?.schema;
    // Only an error code links to the errors page; another word in code (a
    // signing flow's name, a field) stays as it is.
    const said = (response.description ?? "").replace(CODE, (whole, code) =>
      code in refusals ? `[\`${code}\`](/reference/errors/#${code})` : whole,
    );
    const what = [schema ? type(schema) : "", status.startsWith("2") && /successful/i.test(said) ? "" : cell(said)]
      .filter(Boolean)
      .join(" — ");
    return `| ${status} | ${what || "—"} |`;
  });
  return ["| Status | Answer |", "| --- | --- |", ...rows].join("\n");
}

function operationSection(path, method, operation) {
  const secured = (operation.security ?? spec.security ?? []).length > 0;
  return [
    `## ${operation.summary ?? `${method.toUpperCase()} ${path}`}`,
    `\`${method.toUpperCase()} ${path}\`${secured ? " · needs `Authorization: Bearer`" : " · public"}`,
    text(operation.description ?? ""),
    parameters(operation),
    body(operation),
    responses(operation),
  ]
    .filter(Boolean)
    .join("\n\n");
}

// The operations by tag, in the order the document lists them.
const byTag = new Map();
for (const [path, operations] of Object.entries(spec.paths))
  for (const [method, operation] of Object.entries(operations)) {
    const tag = operation.tags?.[0] ?? "other";
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push([path, method, operation]);
  }
const tags = [...byTag.keys()].sort((a, b) => title(a).localeCompare(title(b)));

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
for (const [index, tag] of tags.entries()) {
  const operations = byTag.get(tag);
  const page = [
    "---",
    `title: ${JSON.stringify(title(tag))}`,
    `description: ${JSON.stringify(`The ${title(tag)} operations of the Almena Registry API.`)}`,
    `sidebar: { order: ${index + 1} }`,
    "---",
    "",
    NOTICE,
    "",
    ...operations.map(([path, method, operation]) => `- \`${method.toUpperCase()} ${path}\` — ${cell(operation.summary ?? "")}`),
    "",
    operations.map((entry) => operationSection(...entry)).join("\n\n"),
    "",
  ];
  await writeFile(`${OUT}/${slug(tag)}.md`, page.join("\n"));
}

const schemaPage = [
  "---",
  "title: Schemas",
  "description: Every body the Almena Registry API takes or answers, field by field.",
  `sidebar: { order: ${tags.length + 1} }`,
  "tableOfContents: false",
  "---",
  "",
  NOTICE,
  "",
  ...Object.entries(schemas)
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([name, schema]) => [
      `## ${name}`,
      "",
      schema.description ? `${text(schema.description)}\n` : "",
      fields(schema) || `${type(schema)}`,
      "",
    ]),
];
await writeFile(`${OUT}/schemas.md`, schemaPage.join("\n"));

const count = [...byTag.values()].reduce((all, list) => all + list.length, 0);
const index = [
  "---",
  "title: Almena Registry API",
  "description: Every operation of the API, from its OpenAPI document.",
  "sidebar: { order: 0, label: Overview }",
  "---",
  "",
  NOTICE,
  "",
  `Version ${spec.info.version}: ${count} operations. Every path is on \`https://api.almena.id\`; those under \`/api/v1\` speak JSON. Most need \`Authorization: Bearer <token>\`: an [API token](/integrate/quick-start/) or a sign-in. A refusal answers \`{"detail": "<code>"}\` — every code is in [Errors](/reference/errors/).`,
  "",
  "| Group | Operations |",
  "| --- | --- |",
  ...tags.map((tag) => `| [${title(tag)}](/reference/api/${slug(tag)}/) | ${byTag.get(tag).length} |`),
  `| [Schemas](/reference/api/schemas/) | ${Object.keys(schemas).length} types |`,
  "",
];
await writeFile(`${OUT}/index.md`, index.join("\n"));
console.log(`${OUT}: ${count} operations in ${tags.length} groups, ${Object.keys(schemas).length} schemas`);
